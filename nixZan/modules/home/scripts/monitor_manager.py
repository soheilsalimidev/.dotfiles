#!/usr/bin/env python3

import os
import sys
import json
import hashlib
import subprocess
import time
from pathlib import Path

# Hyprland paths
HIS = os.environ.get("HYPRLAND_INSTANCE_SIGNATURE")
if not HIS:
    print("HYPRLAND_INSTANCE_SIGNATURE not found!")
    sys.exit(1)

# Properly expand environment variables
XDG_RUNTIME_DIR = os.environ.get("XDG_RUNTIME_DIR", "/run/user/" + str(os.getuid()))
SOCKET_PATH = Path(XDG_RUNTIME_DIR) / "hypr" / HIS / ".socket.sock"
SOCKET2_PATH = Path(XDG_RUNTIME_DIR) / "hypr" / HIS / ".socket2.sock"

CONFIG_DIR = Path("~/.config/hypr").expanduser()
CACHE_DIR = CONFIG_DIR / "monitor_cache"
MONITORS_CONF = CONFIG_DIR / "monitors.conf"
CACHE_DIR.mkdir(parents=True, exist_ok=True)

# Debounce time to avoid rapid switching
DEBOUNCE_TIME = 2.0
last_handle_time = 0

# Track recently removed monitors to ignore their immediate re-add
recently_removed_monitors = set()
RECENT_MONITOR_TIMEOUT = 5.0  # seconds

def get_active_monitors():
    """Return list of currently active monitor names and their details."""
    result = subprocess.run(
        ["hyprctl", "monitors", "-j"], capture_output=True, text=True
    )
    monitors = json.loads(result.stdout)
    # Only return monitors that are actually active (not disabled)
    active_monitors = []
    for m in monitors:
        if not m.get("disabled", True) and m.get("width", 0) > 0 and m.get("height", 0) > 0:
            active_monitors.append({
                "name": m["name"],
                "description": m.get("description", ""),
                "make": m.get("make", ""),
                "model": m.get("model", ""),
                "width": m["width"],
                "height": m["height"],
                "refreshRate": m.get("refreshRate", 60.0),
                "x": m["x"],
                "y": m["y"],
                "scale": m.get("scale", 1.0)
            })
    return sorted(active_monitors, key=lambda x: x["name"])

def get_active_monitor():
    """Return the name of the currently focused monitor."""
    result = subprocess.run(
        ["hyprctl", "monitors", "-j"], capture_output=True, text=True
    )
    monitors = json.loads(result.stdout)
    for monitor in monitors:
        if monitor.get("focused", False):
            return monitor["name"]
    return None

def hash_monitor_list(monitors):
    """Generate a unique hash for a list of monitors."""
    monitor_names = [m["name"] for m in monitors]
    return hashlib.md5("".join(sorted(monitor_names)).encode()).hexdigest()

def cache_file_for(monitors):
    """Return the path to the cache file for a given monitor list."""
    h = hash_monitor_list(monitors)
    return CACHE_DIR / f"{h}.last_monitor"

def write_cache(monitors, monitor_name):
    """Write the last used monitor to the cache."""
    cache_file = cache_file_for(monitors)
    cache_file.write_text(monitor_name)

def read_cache(monitors):
    """Read the last used monitor from the cache."""
    cache_file = cache_file_for(monitors)
    if cache_file.exists():
        return cache_file.read_text().strip()
    return None

def focus_monitor(name):
    """Focus the given monitor."""
    subprocess.run(["hyprctl", "dispatch", "focusmonitor", name])

def generate_monitor_config(monitors):
    """Generate monitor configuration lines."""
    config_lines = []
    for monitor in monitors:
        # Use description if available, otherwise construct identifier
        if monitor.get("description"):
            identifier = monitor["description"]
        else:
            identifier = f"{monitor['make']} {monitor['model']}".strip()
            if not identifier:
                identifier = monitor["name"]
        
        # Format refresh rate to 2 decimal places
        refresh_rate = f"{monitor['refreshRate']:.2f}"
        # Remove trailing zeros and decimal point if not needed
        if refresh_rate.endswith('0'):
            refresh_rate = refresh_rate.rstrip('0').rstrip('.')
        
        config_line = f"monitor=desc:{identifier},{monitor['width']}x{monitor['height']}@{refresh_rate},{monitor['x']}x{monitor['y']},{monitor['scale']:.1f}"
        config_lines.append(config_line)
    
    return config_lines

def write_monitors_conf(monitors):
    """Write the monitors.conf file."""
    if not monitors:
        # If no monitors, create empty file or remove it
        if MONITORS_CONF.exists():
            MONITORS_CONF.unlink()
        return
    
    config_lines = generate_monitor_config(monitors)
    
    # Add header
    content = ["# Generated by monitor_manager.py", ""] + config_lines
    
    try:
        print(content)
        MONITORS_CONF.write_text("\n".join(content) + "\n")
        print(f"Updated {MONITORS_CONF}")
    except Exception as e:
        print(f"Failed to write monitors.conf: {e}")

def cleanup_recently_removed():
    """Clean up old entries from recently removed monitors set."""
    global recently_removed_monitors
    current_time = time.time()
    # Remove monitors that were removed more than RECENT_MONITOR_TIMEOUT ago
    recently_removed_monitors = {monitor for monitor in recently_removed_monitors 
                               if current_time - monitor[1] < RECENT_MONITOR_TIMEOUT}

def handle_monitor_removed(monitor_name):
    """Handle monitor removed event."""
    global recently_removed_monitors
    print(f"Monitor removed: {monitor_name}")
    # Add to recently removed set with timestamp
    recently_removed_monitors.add((monitor_name, time.time()))
    # Handle the change normally
    handle_monitor_change()

def handle_monitor_added(monitor_name):
    """Handle monitor added event."""
    global recently_removed_monitors
    print(f"Monitor added: {monitor_name}")
    
    # Check if this monitor was recently removed
    cleanup_recently_removed()
    recently_removed_names = {monitor[0] for monitor in recently_removed_monitors}
    
    if monitor_name in recently_removed_names:
        print(f"Ignoring add event for recently removed monitor: {monitor_name}")
        # Remove from recently removed set
        recently_removed_monitors = {monitor for monitor in recently_removed_monitors 
                                   if monitor[0] != monitor_name}
        return
    
    # Handle the change normally
    handle_monitor_change()

def handle_monitor_change():
    """Handle monitor changes and restore last used monitor."""
    global last_handle_time
    
    # Debounce to avoid rapid switching
    current_time = time.time()
    if current_time - last_handle_time < DEBOUNCE_TIME:
        return
    last_handle_time = current_time
    
    monitors = get_active_monitors()
    print(f"Active monitors: {[m['name'] for m in monitors]}")
    
    # Write monitors.conf
    write_monitors_conf(monitors)

    if not monitors:
        return

    active = get_active_monitor()
    cached = read_cache(monitors)

    # If there's a cached monitor and it's different from current, switch to it
    if cached and cached in [m["name"] for m in monitors] and cached != active:
        print(f"Switching to cached monitor: {cached}")
        focus_monitor(cached)
    elif not active or active not in [m["name"] for m in monitors]:
        # If no active monitor or active monitor not in list, focus first one
        first_monitor = monitors[0]["name"]
        print(f"Focusing first available monitor: {first_monitor}")
        focus_monitor(first_monitor)

    # Update cache with current active monitor
    current_active = get_active_monitor()
    if current_active:
        write_cache(monitors, current_active)

def listen_to_events():
    """Listen to Hyprland socket2 events and react to monitor changes."""
    import socket

    # Check if socket exists
    if not SOCKET2_PATH.exists():
        print(f"Socket not found: {SOCKET2_PATH}")
        print("Make sure Hyprland is running and HYPRLAND_INSTANCE_SIGNATURE is set correctly")
        sys.exit(1)

    sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    try:
        sock.connect(str(SOCKET2_PATH))
    except Exception as e:
        print(f"Failed to connect to socket2: {e}")
        print(f"Socket path: {SOCKET2_PATH}")
        sys.exit(1)

    print("Monitor manager started, listening for events...")
    
    buffer = ""
    while True:
        try:
            data = sock.recv(1024).decode("utf-8")
            if not data:
                break
            buffer += data
            while "\n" in buffer:
                line, buffer = buffer.split("\n", 1)
                line = line.strip()
                if line.startswith("monitorremoved>>"):
                    monitor_name = line.split(">>", 1)[1]
                    handle_monitor_removed(monitor_name)
                elif line.startswith("monitoradded>>"):
                    monitor_name = line.split(">>", 1)[1]
                    handle_monitor_added(monitor_name)
                elif line.startswith("focusedmon>>"):
                    print(f"Focus changed: {line}")
                    handle_monitor_change()
        except Exception as e:
            print(f"Error reading socket: {e}")
            break

if __name__ == "__main__":
    # Initial setup
    handle_monitor_change()
    # Start listening
    listen_to_events()
